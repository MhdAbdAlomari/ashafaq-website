/**
 * Blog article shape.
 *
 * `body` is an ordered list of sections. Each section has an optional H2 heading
 * (omit or set undefined for the intro block) plus one or more paragraphs.
 *
 * A paragraph is either a plain string (no inline links) or a `RichParagraph`
 * with an array of segments — each segment is either raw text or a
 * `{ text, href }` object that becomes an internal <Link>. Keep hrefs relative
 * (starting with "/") so the renderer routes them client-side.
 *
 * `related` is an optional list of related-links cards shown at the end of the
 * article. `closingLine` is an optional final tagline rendered with distinct
 * emphasis (centered/italic).
 */
export type LinkSegment = { text: string; href: string };
export type ParagraphSegment = string | LinkSegment;
export type RichParagraph = { segments: ParagraphSegment[] };
/**
 * A dynamic block resolved at render time by ArticleClient — used when article
 * content should stay in sync with live project data (e.g. the list of
 * neighborhoods where Ashafaq has branches). Add new kinds as needed.
 */
export type DynamicBlock = { dynamic: "branchList" };
export type Paragraph = string | RichParagraph | DynamicBlock;

export type ArticleSection = {
  heading?: string;
  paragraphs: Paragraph[];
};

export type RelatedLink = { label: string; href: string };

export type ArticleBody = {
  sections: ArticleSection[];
  closingLine?: string;
  related?: { title: string; links: RelatedLink[] };
};

export type BlogArticle = {
  slug: string;
  title: string;
  metaTitle: string;
  metaDescription: string;
  category: string;
  excerpt: string;
  body?: ArticleBody;
};

